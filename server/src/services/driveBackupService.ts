export interface BackupHistoryItem {
  id: string;
  timestamp: string;
  trigger: 'manual' | 'scheduled' | 'cli';
  status: 'completed' | 'failed' | 'in_progress';
  dated_folder: string;
  total_records: number;
  file_count: number;
  hierarchy_nodes: string[];
  drive_status: 'synced' | 'local_archived' | 'failed';
  drive_folder_id?: string | null;
  drive_folder_url?: string | null;
  archive_size_bytes?: number;
  duration_ms: number;
  download_url: string;
  error?: string | null;
}

const HISTORY_FILE_PATH = path.join(BACKUP_DIR, 'backup_history.json');
let inMemoryHistory: BackupHistoryItem[] = [];

/**
 * Loads the persistent backup history list
 */
export function getBackupHistoryList(): BackupHistoryItem[] {
  if (inMemoryHistory.length > 0) {
    return inMemoryHistory;
  }
  try {
    if (fs.existsSync(HISTORY_FILE_PATH)) {
      const content = fs.readFileSync(HISTORY_FILE_PATH, 'utf8');
      inMemoryHistory = JSON.parse(content);
      return inMemoryHistory;
    }
  } catch (err) {
    console.warn('[BackupHistory] Error reading history file:', err);
  }
  return [];
}

/**
 * Appends a backup execution result to the history list
 */
function recordBackupHistory(item: BackupHistoryItem): void {
  inMemoryHistory = [item, ...inMemoryHistory.filter((h) => h.id !== item.id)].slice(0, 50);
  try {
    if (!fs.existsSync(BACKUP_DIR)) {
      fs.mkdirSync(BACKUP_DIR, { recursive: true });
    }
    fs.writeFileSync(HISTORY_FILE_PATH, JSON.stringify(inMemoryHistory, null, 2), 'utf8');
  } catch (err) {
    console.warn('[BackupHistory] Failed to write backup history file:', err);
  }
}

/**
 * Generates an official section-wise assessment PDF report
 */
function generateSectionPdfReport(
  filePath: string,
  collegeName: string,
  yearName: string,
  sectionName: string,
  examTitle: string,
  students: any[],
  results: any[]
): Promise<void> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 40, size: 'A4' });
      const stream = fs.createWriteStream(filePath);
      doc.pipe(stream);

      // Header
      doc.fontSize(18).font('Helvetica-Bold').fillColor('#0A192F').text('LogicWhileLiRE Assessment Report', { align: 'center' });
      doc.fontSize(10).font('Helvetica').fillColor('#64748B').text('Live Rank Engine • Official Institutional Audit', { align: 'center' });
      doc.moveDown(0.8);

      // Divider rule
      doc.strokeColor('#2B7FFF').lineWidth(1.5).moveTo(40, doc.y).lineTo(555, doc.y).stroke();
      doc.moveDown(0.8);

      // Section metadata
      doc.fontSize(11).font('Helvetica-Bold').fillColor('#1E293B').text(`Institution: ${collegeName}`);
      doc.fontSize(10).font('Helvetica').fillColor('#334155').text(`Academic Year / Cohort: ${yearName}  |  Section: ${sectionName}`);
      doc.fontSize(10).font('Helvetica').fillColor('#334155').text(`Assessment Title: ${examTitle}`);
      doc.fontSize(9).font('Helvetica-Oblique').fillColor('#64748B').text(`Generated: ${new Date().toISOString()}`);
      doc.moveDown(1);

      // Summary Table
      doc.fontSize(12).font('Helvetica-Bold').fillColor('#0F172A').text('Candidate Performance Breakdown');
      doc.moveDown(0.4);

      if (results.length === 0) {
        doc.fontSize(10).font('Helvetica').fillColor('#64748B').text('No recorded attempts in this section for the assessment period.');
      } else {
        results.slice(0, 30).forEach((r, idx) => {
          doc.fontSize(9).font('Helvetica-Bold').fillColor('#1E293B')
            .text(`${idx + 1}. ${r.student_name || r.name || 'Candidate'} (${r.hall_ticket_no || r.roll_number || 'N/A'}) - Score: ${r.score ?? 0}/${r.max_score ?? 100} (${r.percentage ?? 0}%)`);
        });
      }

      doc.moveDown(1.5);
      doc.fontSize(8).font('Helvetica').fillColor('#94A3B8').text('Confidential & Authoritative • Generated by LogicWhileLiRE Engine • Developed by R. Charan Sai', { align: 'center' });

      doc.end();
      stream.on('finish', () => resolve());
      stream.on('error', reject);
    } catch (err) {
      reject(err);
    }
  });
}

/**
 * Creates a zip archive from a directory
 */
function createArchiveZip(folderPath: string, zipPath: string): Promise<number> {
  return new Promise((resolve, reject) => {
    const output = fs.createWriteStream(zipPath);
    let archive: any;
    if (typeof archiver === 'function') {
      archive = archiver('zip', { zlib: { level: 9 } });
    } else if (archiver?.default && typeof archiver.default === 'function') {
      archive = archiver.default('zip', { zlib: { level: 9 } });
    } else if (archiver?.ZipArchive) {
      archive = new archiver.ZipArchive({ zlib: { level: 9 } });
    } else {
      archive = (archiver.default || archiver)('zip', { zlib: { level: 9 } });
    }

    output.on('close', () => {
      try {
        const stats = fs.statSync(zipPath);
        resolve(stats.size);
      } catch {
        resolve(0);
      }
    });
    archive.on('error', reject);

    archive.pipe(output);
    archive.directory(folderPath, false);
    archive.finalize();
  });
}

/**
 * Core Phase 3 Backup Job:
 * Exports students, exams, results, and audit log to dated folders (college / year / section)
 * and uploads to Google Drive if credentials exist.
 */
export async function executeGoogleDriveBackup(options: {
  trigger?: 'manual' | 'scheduled' | 'cli';
  adminId?: string;
}): Promise<BackupHistoryItem> {
  const startTime = Date.now();
  const trigger = options.trigger || 'manual';
  const now = new Date();
  const dateStr = now.toISOString().split('T')[0]; // YYYY-MM-DD
  const timeStr = now.toISOString().replace(/[:.]/g, '-').slice(11, 19);
  const backupId = `backup_${dateStr}_${timeStr}`;

  // Dated root folder
  const datedFolderRelative = `${dateStr}/${backupId}`;
  const localDatedFolderPath = path.join(BACKUP_DIR, dateStr, backupId);
  fs.mkdirSync(localDatedFolderPath, { recursive: true });

  // 1. Fetch live data from Supabase
  const [
    studentsRaw,
    candidatesRaw,
    collegesRaw,
    sectionsRaw,
    cohortsRaw,
    academicYearsRaw,
    examsRaw,
    examCodesRaw,
    resultsRaw,
    attemptsRaw,
    auditLogsRaw,
  ] = await Promise.all([
    supabase.from('students').select('*').then((r) => r.data || []),
    supabase.from('participants').select('*').then((r) => (r.data?.length ? r.data : supabase.from('candidates').select('*').then((c) => c.data || []))),
    supabase.from('colleges').select('*').then((r) => r.data || []),
    supabase.from('sections').select('*').then((r) => r.data || []),
    supabase.from('cohorts').select('*').then((r) => r.data || []),
    supabase.from('academic_years').select('*').then((r) => r.data || []),
    supabase.from('exams').select('*').then((r) => r.data || []),
    supabase.from('exam_codes').select('*').then((r) => r.data || []),
    supabase.from('results').select('*').then((r) => r.data || []),
    supabase.from('exam_sessions').select('*').then((r) => (r.data?.length ? r.data : supabase.from('attempts').select('*').then((a) => a.data || []))),
    supabase.from('audit_log').select('*').limit(3000).then((r) => r.data || []),
  ]);

  const allStudents = sanitizeRecord([...studentsRaw, ...candidatesRaw]);
  const allExams = sanitizeRecord([...examsRaw, ...examCodesRaw]);
  const allResults = sanitizeRecord(resultsRaw);
  const allAttempts = sanitizeRecord(attemptsRaw);
  const cleanAuditLogs = sanitizeRecord(auditLogsRaw);

  const totalRecords = allStudents.length + allExams.length + allResults.length + cleanAuditLogs.length;
  let fileCount = 0;
  const hierarchyNodesSet = new Set<string>();

  // 2. Write Global Level Exports
  const globalDir = path.join(localDatedFolderPath, 'global');
  fs.mkdirSync(globalDir, { recursive: true });

  // Audit Log CSV & Excel
  const auditCsv = convertToCsv(cleanAuditLogs);
  fs.writeFileSync(path.join(globalDir, 'audit_log.csv'), auditCsv, 'utf8');
  fileCount++;

  const auditWb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(auditWb, XLSX.utils.json_to_sheet(cleanAuditLogs), 'Audit_Log');
  fs.writeFileSync(path.join(globalDir, 'audit_log.xlsx'), XLSX.write(auditWb, { type: 'buffer', bookType: 'xlsx' }));
  fileCount++;

  // Exams JSON & CSV
  const examsCsv = convertToCsv(allExams);
  fs.writeFileSync(path.join(globalDir, 'exams.csv'), examsCsv, 'utf8');
  fs.writeFileSync(path.join(globalDir, 'exams.json'), JSON.stringify(allExams, null, 2), 'utf8');
  fileCount += 2;

  // Master Results Excel
  const resultsWb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(resultsWb, XLSX.utils.json_to_sheet(allResults), 'All_Results');
  fs.writeFileSync(path.join(globalDir, 'master_results.xlsx'), XLSX.write(resultsWb, { type: 'buffer', bookType: 'xlsx' }));
  fileCount++;

  // 3. Organize Hierarchy Exports: college / year / section
  // Map lookups for friendly folder names
  const collegeMap = new Map<string, string>();
  for (const c of collegesRaw) collegeMap.set(String(c.id), c.name || c.code || `College_${c.id}`);

  const sectionMap = new Map<string, any>();
  for (const s of sectionsRaw) sectionMap.set(String(s.id), s);

  // Group students by (college / year / section)
  const groupedHierarchy = new Map<string, { collegeName: string; yearName: string; sectionName: string; students: any[] }>();

  for (const stu of allStudents) {
    const colName = (stu.college_id ? collegeMap.get(String(stu.college_id)) : null) || stu.college_name || 'General_College';
    const yrName = String(stu.year_of_passing || stu.cohort_name || stu.academic_year || 'Current_Year');
    const secName = String(stu.section || stu.section_name || 'Section_A');

    const cleanCol = colName.replace(/[^a-zA-Z0-9_-]/g, '_');
    const cleanYr = yrName.replace(/[^a-zA-Z0-9_-]/g, '_');
    const cleanSec = secName.replace(/[^a-zA-Z0-9_-]/g, '_');

    const pathKey = `${cleanCol}/${cleanYr}/${cleanSec}`;
    if (!groupedHierarchy.has(pathKey)) {
      groupedHierarchy.set(pathKey, {
        collegeName: cleanCol,
        yearName: cleanYr,
        sectionName: cleanSec,
        students: [],
      });
    }
    groupedHierarchy.get(pathKey)!.students.push(stu);
  }

  // Ensure at least one default node exists if database is fresh
  if (groupedHierarchy.size === 0) {
    groupedHierarchy.set('Default_Institution/2026/Section_A', {
      collegeName: 'Default_Institution',
      yearName: '2026',
      sectionName: 'Section_A',
      students: [],
    });
  }

  // Write files inside each (college / year / section) folder
  for (const [nodePath, nodeData] of groupedHierarchy.entries()) {
    hierarchyNodesSet.add(nodePath);
    const nodeDir = path.join(localDatedFolderPath, 'colleges', nodePath);
    fs.mkdirSync(nodeDir, { recursive: true });

    // Students roster Excel & CSV
    const rosterWb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(rosterWb, XLSX.utils.json_to_sheet(nodeData.students), 'Roster');
    fs.writeFileSync(path.join(nodeDir, 'students_roster.xlsx'), XLSX.write(rosterWb, { type: 'buffer', bookType: 'xlsx' }));
    fs.writeFileSync(path.join(nodeDir, 'students_roster.csv'), convertToCsv(nodeData.students), 'utf8');
    fileCount += 2;

    // Results in this section
    const nodeResults = allAttempts.filter((att: any) =>
      nodeData.students.some((s: any) => (s.hall_ticket || s.roll_number) === (att.hall_ticket_no || att.hall_ticket))
    );

    const sectionResultsWb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(sectionResultsWb, XLSX.utils.json_to_sheet(nodeResults), 'Exam_Results');
    fs.writeFileSync(path.join(nodeDir, 'section_results.xlsx'), XLSX.write(sectionResultsWb, { type: 'buffer', bookType: 'xlsx' }));
    fs.writeFileSync(path.join(nodeDir, 'section_results.csv'), convertToCsv(nodeResults), 'utf8');
    fileCount += 2;

    // Section Assessment PDF Report
    const pdfPath = path.join(nodeDir, 'official_assessment_report.pdf');
    try {
      await generateSectionPdfReport(
        pdfPath,
        nodeData.collegeName,
        nodeData.yearName,
        nodeData.sectionName,
        'Campus Comprehensive Benchmark',
        nodeData.students,
        nodeResults
      );
      fileCount++;
    } catch (pdfErr) {
      console.warn(`[Backup PDF] Notice on ${nodePath}:`, pdfErr);
    }
  }

  // 4. Create ZIP archive
  const zipPath = path.join(BACKUP_DIR, `${backupId}.zip`);
  const archiveSizeBytes = await createArchiveZip(localDatedFolderPath, zipPath);

  // 5. Apply 30-day retention
  pruneOldBackups(30);

  // 6. Google Drive Cloud Sync (if configured via env vars)
  let driveStatus: BackupHistoryItem['drive_status'] = 'local_archived';
  let driveFolderId: string | null = null;
  let driveFolderUrl: string | null = null;
  let backupError: string | null = null;

  if (isGoogleDriveConfigured()) {
    try {
      const cfg = getGoogleDriveConfig();
      const token = await getGoogleServiceAccountToken();

      // Create dated folder inside configured root folder
      const rootFolder = await createDriveFolder(token, `LogicWhileLiRE_${dateStr}_${backupId}`, cfg.rootFolderId);
      driveFolderId = rootFolder.id;
      driveFolderUrl = `https://drive.google.com/drive/folders/${driveFolderId}`;

      // Recursively upload dated directory tree
      await uploadDirectoryToDrive(token, localDatedFolderPath, rootFolder.id);

      driveStatus = 'synced';
    } catch (err: any) {
      console.error('[GoogleDrive] Sync failed:', err.message);
      driveStatus = 'failed';
      backupError = `Google Drive upload failed: ${err.message}`;
    }
  }

  const durationMs = Date.now() - startTime;

  // 7. Write Manifest into backup folder
  const manifest = {
    version: '4.0.0',
    backupId,
    timestamp: now.toISOString(),
    trigger,
    dated_folder: datedFolderRelative,
    total_records: totalRecords,
    file_count: fileCount,
    hierarchy_nodes: Array.from(hierarchyNodesSet),
    drive_status: driveStatus,
    drive_folder_id: driveFolderId,
    archive_size_bytes: archiveSizeBytes,
    duration_ms: durationMs,
  };
  fs.writeFileSync(path.join(localDatedFolderPath, 'manifest.json'), JSON.stringify(manifest, null, 2), 'utf8');

  // 8. Record to persistent history
  const historyItem: BackupHistoryItem = {
    id: backupId,
    timestamp: now.toISOString(),
    trigger,
    status: backupError ? 'failed' : 'completed',
    dated_folder: datedFolderRelative,
    total_records: totalRecords,
    file_count: fileCount,
    hierarchy_nodes: Array.from(hierarchyNodesSet),
    drive_status: driveStatus,
    drive_folder_id: driveFolderId,
    drive_folder_url: driveFolderUrl,
    archive_size_bytes: archiveSizeBytes,
    duration_ms: durationMs,
    download_url: `/api/admin/backup/download?id=${backupId}`,
    error: backupError,
  };

  recordBackupHistory(historyItem);
  return historyItem;
}
